/**
 * Generates swig-sources.gypi containing the full list of
 * SWIG-generated .cxx source files for node-gyp.
 *
 * This is the reliable way to pass a large number of source files
 * to node-gyp on all platforms (avoids <!@ whitespace-splitting issues).
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SWIG_DIR = path.join(ROOT, 'swig');
const OUTPUT = path.join(ROOT, 'swig-sources.gypi');

if (!fs.existsSync(SWIG_DIR)) {
  console.error('Error: swig/ directory not found.');
  console.error('Run "npm run generate-bindings" first.');
  process.exit(1);
}

const files = fs.readdirSync(SWIG_DIR)
  .filter(f => f.endsWith('.cxx'))
  .sort()
  .map(f => `      'swig/${f}'`);

if (files.length === 0) {
  console.error('Error: No .cxx files found in swig/.');
  process.exit(1);
}

const content = `# Auto-generated by scripts/write-swig-sources.cjs
# Do not edit manually — run "npm run generate-sources" to regenerate
{
  'sources': [
${files.join(',\n')}
  ]
}
`;

fs.writeFileSync(OUTPUT, content, 'utf-8');
console.log(`Generated ${OUTPUT} with ${files.length} source files.`);
